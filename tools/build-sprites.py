#!/usr/bin/env python3
"""Rasterise art/*.svg into per-layer alpha sheets and regenerate Frames.js.

Needs `rsvg-convert` and ImageMagick (`magick`); no network, no Python imaging
libraries. Run from anywhere:  tools/build-sprites.py

Frames are ordered by pose name, then frame number, so adding a frame moves
later indices; Frames.js is regenerated in step, so that is invisible.
"""

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "art"
ASSETS = ROOT / "assets"
CELL_W, CELL_H = 40, 25
LAYERS = ("fill", "ink", "accent")
SCALES = {"1x": 1, "2x": 2}
NAME = re.compile(r"^(?P<pose>[a-z]+(?:-[a-z]+)*?)(?:-(?P<n>\d+))?\.svg$")


def collect():
    """pose -> [svg paths in frame order]"""
    poses = {}
    for path in sorted(ART.glob("*.svg")):
        m = NAME.match(path.name)
        if not m:
            sys.exit(f"unrecognised art file name: {path.name}")
        poses.setdefault(m["pose"], []).append((int(m["n"] or 1), path))
    out = {}
    for pose in sorted(poses):
        frames = sorted(poses[pose])
        nums = [n for n, _ in frames]
        if nums != list(range(1, len(nums) + 1)):
            sys.exit(f"{pose}: frames must be numbered 1..n, got {nums}")
        out[pose] = [p for _, p in frames]
    return out


def render(svg, layer, scale, dest):
    """Render one layer of one frame; the other groups are hidden by CSS."""
    hidden = ",".join(f"#{l}" for l in LAYERS if l != layer)
    with tempfile.NamedTemporaryFile("w", suffix=".css") as css:
        # Sheets are white: MultiEffect colorization scales the tint by the
        # pixel's luminance, so a black mask stays black whatever the tint.
        css.write(f"{hidden}{{display:none}}\nrect{{fill:#fff}}\n")
        css.flush()
        subprocess.run(
            ["rsvg-convert", "-w", str(CELL_W * scale), "-h", str(CELL_H * scale),
             "-s", css.name, "-o", str(dest), str(svg)],
            check=True)


def write_frames_js(poses):
    index, n = {}, 0
    for pose, files in poses.items():
        index[pose] = list(range(n, n + len(files)))
        n += len(files)
    body = json.dumps(index, indent=2)
    (ROOT / "Frames.js").write_text(
        "// GENERATED by tools/build-sprites.py -- do not edit by hand.\n"
        ".pragma library\n\n"
        f"var CELL_W = {CELL_W}\n"
        f"var CELL_H = {CELL_H}\n"
        f"var COUNT = {n}\n"
        "// pose -> sheet frame indices, in animation order\n"
        f"var POSES = {body}\n")
    return n


def main():
    poses = collect()
    ASSETS.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        for tag, scale in SCALES.items():
            for layer in LAYERS:
                cells = []
                for files in poses.values():
                    for i, svg in enumerate(files):
                        cell = Path(tmp) / f"{tag}-{layer}-{len(cells):03d}.png"
                        render(svg, layer, scale, cell)
                        cells.append(str(cell))
                subprocess.run(
                    ["magick", *cells, "+append", "-strip",
                     str(ASSETS / f"valkiria-{tag}-{layer}.png")],
                    check=True)
    total = write_frames_js(poses)
    print(f"{total} frames, {len(poses)} poses")


if __name__ == "__main__":
    main()
